function numToThaiWord(n) {
  if (n < 10) return THAI_NUM_WORD[n];
  if (n === 10) return 'สิบ';
  if (n === 20) return 'ยี่สิบ';
  return 'สิบ' + (n % 10 === 1 ? 'เอ็ด' : THAI_NUM_WORD[n % 10]);
}

